#!/usr/bin/env python3
"""gen_table.py: write table16.bend (the crc16_tbl array of Pico-PIO-USB's usb_crc.c as a Bend list)."""
import re
import sys
from pathlib import Path

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
body = re.search(r"crc16_tbl\[256\]\s*=\s*\{(.*?)\};", src.read_text(), re.S)
if not body:
    sys.exit(f"no crc16_tbl[256] in {src}")
vals = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body.group(1))]
if len(vals) != 256:
    sys.exit(f"crc16_tbl has {len(vals)} entries, want 256")
dst.write_text("import Base\n\n# generated by gen_table.py from " + src.name + ": crc16_tbl[0..255]\n"
               "def table16() -> List<U32>:\n  [" + ", ".join(map(str, vals)) + "]\n")
